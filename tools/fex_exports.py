#!/usr/bin/env python3
"""Generate typed C adapters from Clang declarations, preserving each host function's ABI.

The generated translation unit includes the original runtime source. Calls therefore use its
real types, including private structs and callback typedefs; no incompatible function-pointer
casts or guessed signatures are needed. The x86 guest's GPR/XMM/stack arguments are unpacked
before the compiler emits the ARM64 call.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess

INTEGER_REGISTERS = (7, 6, 2, 1, 8, 9)  # x86 RDI, RSI, RDX, RCX, R8, R9


def generate(source, output, compiler, flags, target='aarch64-linux-gnu'):
    command = [compiler, f'--target={target}', '-std=c11', '-D_DEFAULT_SOURCE', *flags,
               '-Xclang', '-ast-dump=json', '-fsyntax-only', str(source)]
    result = subprocess.run(command, check=True, capture_output=True, text=True)
    tree = json.loads(result.stdout)
    source_text = source.read_text()

    def guest_abi(node):
        if re.search(r'\b(?:ABI|sysv_abi)\b', node.get('type', {}).get('qualType', '')):
            return True
        # Clang drops the ignored ARM sysv_abi spelling when another attribute (for
        # example noreturn) canonicalizes the type. The declaration still names ABI.
        location = node.get('loc', {})
        begin = node.get('range', {}).get('begin', {})
        if 'includedFrom' in location or 'offset' not in location or 'offset' not in begin:
            return False
        return bool(re.search(r'\bABI\b', source_text[begin['offset']:location['offset']]))

    functions = [node for node in tree['inner'] if node.get('kind') == 'FunctionDecl'
                 and guest_abi(node)
                 and any(child['kind'] == 'CompoundStmt' for child in node.get('inner', []))]
    # The runtime's feature-test macros (_GNU_SOURCE, _XOPEN_SOURCE) must precede libc headers.
    lines = ['/* Generated by tools/fex_exports.py; do not edit. */',
             f'#include {json.dumps(str(source.resolve()))}',
             '#include "fex_exports.h"', '#include <string.h>', '']
    entries = []
    for function in functions:
        if function.get('variadic'):
            raise ValueError(f"variadic guest export needs an explicit adapter: {function['name']}")
        name = function['name']
        return_type = function['type']['qualType'].split('(', 1)[0].replace('ABI ', '').strip()
        integer = vector = stack = 0
        arguments = []
        lines.append(f'static void fex_invoke_{name}(TempestFexFrame *frame) {{')
        for index, param in enumerate(p for p in function.get('inner', []) if p['kind'] == 'ParmVarDecl'):
            kind = param['type']['qualType']
            scalar_type = param['type'].get('desugaredQualType', kind)
            floating = scalar_type in ('float', 'double')
            if floating and vector < 8:
                value = f'frame->xmm[{vector}][0]'
                vector += 1
            elif not floating and integer < len(INTEGER_REGISTERS):
                value = f'frame->gpr[{INTEGER_REGISTERS[integer]}]'
                integer += 1
            else:
                value = f'*(const uint64_t *)(frame->rsp + {8 + stack * 8})'
                stack += 1
            if floating:
                lines.extend([f'    uint64_t bits{index} = {value};',
                              f'    {kind} arg{index};',
                              f'    memcpy(&arg{index}, &bits{index}, sizeof(arg{index}));'])
                arguments.append(f'arg{index}')
            else:
                arguments.append(f'({kind})(uintptr_t)({value})')
        call = f'{name}({", ".join(arguments)})'
        if return_type == 'void':
            lines.append(f'    {call};')
        elif return_type in ('float', 'double'):
            lines.extend([f'    {return_type} result = {call};',
                          '    frame->xmm[0][0] = 0;',
                          '    memcpy(&frame->xmm[0][0], &result, sizeof(result));'])
        else:
            lines.extend([f'    __auto_type result = {call};',
                          '    uint64_t bits = (uint64_t)(uintptr_t)result;',
                          '    frame->gpr[0] = sizeof(result) <= 4 ? (uint32_t)bits : bits;'])
        if not arguments and return_type == 'void':
            lines.append('    (void)frame;')
        lines.extend(['}', ''])
        entries.append(f'    {{"{name}", (void *){name}, fex_invoke_{name}, {stack * 8}}},')
    stem = re.sub(r'\W', '_', source.stem)
    lines.extend([f'const TempestFexExport tempest_fex_{stem}[] = {{', *entries, '};',
                  f'const size_t tempest_fex_{stem}_count = {len(entries)};', ''])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines))
    print(f'{source.name}: {len(entries)} typed FEX adapters')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--compiler', default='clang')
    parser.add_argument('--target', default='aarch64-linux-gnu')
    args, flags = parser.parse_known_args()
    generate(args.source, args.out, args.compiler, flags, args.target)


if __name__ == '__main__':
    main()
